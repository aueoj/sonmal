const normalize = value => String(value ?? '').normalize('NFC').replace(/[.,!?·…"'()。！？]/gu, ' ').replace(/\s+/gu, ' ').trim();
const byWord = new Map();
for (const sign of WORD_SIGNS) {
  for (const term of [sign.word, ...sign.aliases]) {
    const key = normalize(term);
    if (byWord.has(key) && byWord.get(key) !== sign) throw new Error(`중복 표현: ${key}`);
    byWord.set(key, sign);
  }
}
export function lookupWord(word) { return byWord.get(normalize(word)) ?? null; }

// 긴 표현을 먼저 찾되, 미등록 단어의 일부를 잘못 수어로 바꾸지 않는다.
// 문장의 한국어 어순을 유지하는 낱말 연습이며 한국수어 문장 번역은 아니다.
export function planUtterance(text) {
  const tokens = normalize(text).split(' ').filter(Boolean), out = [];
  for (let i = 0; i < tokens.length;) {
    let found = false;
    for (let end = Math.min(tokens.length, i + 5); end > i; end--) {
      const phrase = tokens.slice(i, end).join(' '), sign = lookupWord(phrase);
      if (sign) { out.push({ kind: 'word', text: phrase, sign }); i = end; found = true; break; }
    }
    if (!found) out.push({ kind: 'spell', text: tokens[i++] });
  }
  return out;
}
