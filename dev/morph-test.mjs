/* 활용한 말도 기본형 수어로 찾는가, 엉뚱한 말을 수어로 바꾸지 않는가 */
import { matchToken } from '../js/words.js';

const SHOULD = {
  만들다: ['만들었어', '만든거야', '만든', '만들', '만드는', '만듭니다', '만들고', '만들자', '만들어줘', '만들었어요', '만들었는데', '만드니까', '만들래'],
  먹다: ['먹는다', '먹었어', '먹은', '먹을', '먹자', '먹고', '먹었습니다'],
  만나다: ['만났어', '만난', '만나자', '만났습니다', '만날'],
  슬퍼요: ['슬펐어', '슬프다', '슬퍼서', '슬픈'],
  배고파요: ['배고팠어', '배고프다', '배고픈'],
  피곤해요: ['피곤했어', '피곤해서', '피곤한'],
  무서워요: ['무서웠어', '무서운', '무서워서'],
  도와주세요: ['도와줘', '도와', '도와주세요', '도왔어'],
  화나요: ['화났어', '화난'],
  아파요: ['아팠어', '아픈', '아파서'],
  기뻐요: ['기뻤어', '기쁜'],
  좋아요: ['좋았어', '좋은', '좋네'],
  괜찮아요: ['괜찮았어', '괜찮은'],
  걱정돼요: ['걱정됐어', '걱정돼서'],
  행복해요: ['행복했어', '행복한'],
  가다: ['갔어', '가요', '간다', '가자', '갔습니다'],
  오다: ['와요', '왔어', '오세요', '온다'],
  배우다: ['배워요', '배웠어', '배우고'],
  있다: ['있어요', '있었어', '있는'],
  없다: ['없어요', '없었어', '없는'],
  자다: ['자요', '잤어', '자고', '잔다'],
  보다: ['봐요', '봤어', '본다'],
  듣다: ['들어요', '들었어'],
  읽다: ['읽어요', '읽었어', '읽는다'],
  맛있다: ['맛있어요', '맛있었어', '맛있는'],
  맛없다: ['맛없어요', '맛없었어']
};
const SHOULD_NOT = ['글', '금', '날', '그래', '그림', '하나', '여자', '사과', '나무', '마음', '만세', '비밀', '비싸요'];

const bad = [];
let ok = 0;
for (const [want, forms] of Object.entries(SHOULD)) for (const f of forms) {
  const got = matchToken(f).sign?.word;
  if (got === want) ok++; else bad.push(`${f} → ${got ?? '(못 찾음)'}  (${want} 이어야 함)`);
}
for (const f of SHOULD_NOT) {
  const got = matchToken(f).sign?.word;
  if (got) bad.push(`${f} → ${got}  (수어로 바꾸면 안 됨)`); else ok++;
}
console.log(`맞게 찾음 ${ok}개`);
for (const b of bad) console.log('  ✕ ' + b);
process.exit(bad.length ? 1 : 0);
